"""Generate observability/.env for self-hosted Langfuse, and point the
backend at it.

Creates random secrets for every service, disables Langfuse telemetry, and
pre-creates an organisation, project, login and API keys so no manual setup
is needed. Adds the project's keys to backend/.env. Safe to re-run: existing
values are kept.

    python3 observability/setup_env.py
"""

import secrets
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
LANGFUSE_ENV = ROOT / "observability" / ".env"
BACKEND_ENV = ROOT / "backend" / ".env"


def read_env(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    pairs = (line.split("=", 1) for line in path.read_text().splitlines() if "=" in line and not line.startswith("#"))
    return {key.strip(): value.strip() for key, value in pairs}


def main() -> None:
    existing = read_env(LANGFUSE_ENV)
    token = lambda: secrets.token_hex(24)  # noqa: E731

    postgres_password = existing.get("POSTGRES_PASSWORD", token())
    minio_password = existing.get("MINIO_ROOT_PASSWORD", token())
    public_key = existing.get("LANGFUSE_INIT_PROJECT_PUBLIC_KEY", f"pk-lf-{secrets.token_hex(16)}")
    secret_key = existing.get("LANGFUSE_INIT_PROJECT_SECRET_KEY", f"sk-lf-{secrets.token_hex(16)}")
    password = existing.get("LANGFUSE_INIT_USER_PASSWORD", secrets.token_urlsafe(12))

    values = {
        "TELEMETRY_ENABLED": "false",
        "SALT": existing.get("SALT", token()),
        "ENCRYPTION_KEY": existing.get("ENCRYPTION_KEY", secrets.token_hex(32)),
        "NEXTAUTH_SECRET": existing.get("NEXTAUTH_SECRET", token()),
        "POSTGRES_PASSWORD": postgres_password,
        "DATABASE_URL": f"postgresql://postgres:{postgres_password}@postgres:5432/postgres",
        "CLICKHOUSE_PASSWORD": existing.get("CLICKHOUSE_PASSWORD", token()),
        "REDIS_AUTH": existing.get("REDIS_AUTH", token()),
        "MINIO_ROOT_PASSWORD": minio_password,
        "LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY": minio_password,
        "LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY": minio_password,
        "LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY": minio_password,
        "LANGFUSE_INIT_ORG_ID": "clear-path",
        "LANGFUSE_INIT_ORG_NAME": "Clear Path",
        "LANGFUSE_INIT_PROJECT_ID": "clear-path-assistant",
        "LANGFUSE_INIT_PROJECT_NAME": "Clear Path Assistant",
        "LANGFUSE_INIT_PROJECT_PUBLIC_KEY": public_key,
        "LANGFUSE_INIT_PROJECT_SECRET_KEY": secret_key,
        "LANGFUSE_INIT_USER_EMAIL": existing.get("LANGFUSE_INIT_USER_EMAIL", "admin@clearpath.local"),
        "LANGFUSE_INIT_USER_NAME": "Clear Path Admin",
        "LANGFUSE_INIT_USER_PASSWORD": password,
    }
    LANGFUSE_ENV.write_text(
        "# Generated by observability/setup_env.py; local secrets, never commit.\n"
        + "".join(f"{key}={value}\n" for key, value in values.items())
    )

    backend = read_env(BACKEND_ENV)
    additions = {
        "LANGFUSE_PUBLIC_KEY": public_key,
        "LANGFUSE_SECRET_KEY": secret_key,
        "LANGFUSE_HOST": "http://localhost:3000",
    }
    missing = {k: v for k, v in additions.items() if k not in backend}
    if missing:
        with BACKEND_ENV.open("a") as env:
            env.write("\n# Self-hosted Langfuse tracing (observability/setup_env.py)\n")
            env.write("".join(f"{key}={value}\n" for key, value in missing.items()))

    print(f"Wrote {LANGFUSE_ENV.relative_to(ROOT)}"
          + (f" and added Langfuse keys to {BACKEND_ENV.relative_to(ROOT)}" if missing else ""))
    print(f"Langfuse login: {values['LANGFUSE_INIT_USER_EMAIL']} / {password}")


if __name__ == "__main__":
    main()
